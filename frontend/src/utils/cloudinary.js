/**
 * Cloudinary image helpers (preset: ELIJAYS)
 */

export const CLOUDINARY_PRESET = 'ELIJAYS';

export const isCloudinaryUrl = (url) =>
  typeof url === 'string' && url.includes('res.cloudinary.com');

export const isBlobUrl = (url) =>
  typeof url === 'string' && url.startsWith('blob:');

// Uploaded files belong to the API host; public storefront assets stay local.
export const resolveMediaUrl = (url) => {
  if (typeof url !== 'string') return '';
  if (!/^\/?uploads\//.test(url)) return url;
  const apiBase = import.meta.env?.VITE_API_URL || '/api';
  const origin = new URL(apiBase, globalThis.location?.origin || 'http://localhost').origin;
  return `${origin}/${url.replace(/^\//, '')}`;
};

/** Safe src for <img> — blob URLs expire after navigation/reload and must not be persisted. */
export const resolveDisplayImageUrl = (url, { width = 400 } = {}) => {
  if (!url || isBlobUrl(url)) return '';
  if (typeof url === 'object') return getImageSrc(url, width <= 480 ? 'thumbnail' : 'optimized');
  return isCloudinaryUrl(url) ? optimizeCloudinaryUrl(url, { width }) : resolveMediaUrl(url);
};

/** Raw Cloudinary URL for DB storage (transforms applied at display time). */
export const getPersistImageUrl = (item) => {
  if (!item) return '';
  if (typeof item === 'string') return item;
  return item.url || item.secure_url || '';
};

export const revokeBlobUrl = (url) => {
  if (isBlobUrl(url)) {
    try {
      URL.revokeObjectURL(url);
    } catch {
      /* ignore */
    }
  }
};

/**
 * @param {string|{ url?: string, optimized?: string, thumbnail?: string }} image
 */
export const getImageSrc = (image, variant = 'optimized') => {
  if (!image) return '';
  if (typeof image === 'string') {
    return variant === 'thumbnail'
      ? optimizeCloudinaryUrl(image, { width: 400 })
      : optimizeCloudinaryUrl(image, { width: 800 });
  }
  if (variant === 'thumbnail') return resolveMediaUrl(image.thumbnail || image.optimized || image.url || image.secure_url || '');
  return resolveMediaUrl(image.optimized || image.url || image.secure_url || image.thumbnail || '');
};

/**
 * Extract display URL from upload API response item (string legacy or JSON object).
 */
export const getUploadUrl = (item) => {
  if (!item) return '';
  if (typeof item === 'string') return item;
  return item.optimized || item.url || item.secure_url || '';
};

/** Store-friendly JSON for product.images column */
export const toImageJson = (item) => {
  if (!item) return null;
  if (typeof item === 'string') {
    return {
      url: item,
      optimized: optimizeCloudinaryUrl(item, { width: 800 }),
      thumbnail: optimizeCloudinaryUrl(item, { width: 400 }),
    };
  }
  return {
    url: item.url || item.secure_url,
    optimized: item.optimized || getUploadUrl(item),
    thumbnail: item.thumbnail || optimizeCloudinaryUrl(getUploadUrl(item), { width: 400 }),
    public_id: item.public_id,
  };
};

// Remove only the delivery transform generated by this helper. An underscore
// alone does not identify a transform: it is valid in folders and public IDs.
const stripCloudinaryTransforms = (pathAfterUpload) =>
  pathAfterUpload.replace(/^f_auto,q_auto,w_\d+,c_[a-z]+(?:,h_\d+)?\//, '');

export const optimizeCloudinaryUrl = (url, { width = 800, height, crop = 'limit' } = {}) => {
  if (!url || !isCloudinaryUrl(url)) return resolveMediaUrl(url);
  const marker = '/upload/';
  const idx = url.indexOf(marker);
  if (idx === -1) return url;
  const base = url.slice(0, idx + marker.length);
  const assetPath = stripCloudinaryTransforms(url.slice(idx + marker.length));
  const transforms = [`f_auto`, `q_auto`, `w_${width}`, `c_${crop}`];
  if (height) transforms.push(`h_${height}`);
  return `${base}${transforms.join(',')}/${assetPath}`;
};

/** Hero carousel — fills viewport without aggressive zoom */
export const heroImageUrl = (url) =>
  isCloudinaryUrl(url)
    ? optimizeCloudinaryUrl(url, { width: 1600, height: 900, crop: 'fill' })
    : url;

export const parseProductImages = (images) => {
  if (!images) return [];
  let list = images;
  if (typeof images === 'string') {
    try {
      list = JSON.parse(images);
    } catch {
      return [];
    }
  }
  if (!Array.isArray(list)) return [];
  return list.map((img) => (typeof img === 'string' ? toImageJson(img) : img)).filter(Boolean);
};
